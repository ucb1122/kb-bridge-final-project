export function conversationalReply(question){
  const text=String(question).trim();
  if(/코비.{0,12}(?:누구|탄생|태어|만들|왜|나이|몇 살|몇살|코끼리)|(?:왜|어째서).{0,12}코끼리|(?:너는|넌|코비는).{0,12}(?:어떻게|왜).{0,8}(?:태어|탄생|만들)/.test(text)){
    if(/나이|몇 살|몇살/.test(text))return '코비의 나이는 아직 정해지지 않았어요.';
    return '코비는 지수, 준용, 황혁, 채영, 정환, 희헌 여섯 사람이 함께 만든 KO-B의 코끼리 캐릭터예요. 코끼리의 발이 위험을 감지한다는 발상에서, 상권의 폐업 위험 신호를 미리 살피고 준비하도록 돕는 서비스의 상징이 됐어요.';
  }
  if(/(?:이름|누구|정체).*(?:뭐|누구|알려|소개)|(?:너|넌|당신).*(?:이름|누구)/.test(text))
    return '저는 KO-B의 안내 챗봇 코비예요. 상권 분석, 회복 플래너, 상담 준비 화면을 이해하는 데 도움을 드릴게요.';
  if(/^(?:안녕|안녕하세요|반가워|하이)[!?.\s]*$/.test(text))
    return '안녕하세요! 저는 KO-B 안내 챗봇 코비예요. 어떤 점이 궁금하세요?';
  if(/(?:오늘|내일|이번 주|현재).{0,8}날씨|날씨.{0,8}(?:어때|알려|어떻)/.test(text))
    return '실시간 날씨는 이 챗봇에서 확인할 수 없어요. 지역과 날짜를 정해 기상청 날씨누리에서 확인해 주세요.';
  return null;
}
